"""Write docs/dependency-licenses.md from the installed packages pinned in requirements.txt.

Run: .venv/bin/python scripts/list_dependency_licenses.py
"""
import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def licence(dist):
    meta = dist.metadata
    expression = meta.get("License-Expression")
    if expression:
        return expression
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return ", ".join(classifiers)
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:80] if text else "not stated in package metadata"


def main():
    rows = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        match = re.match(r"([A-Za-z0-9_.-]+)==(\S+)", line.strip())
        if not match:
            continue
        name, version = match.groups()
        dist = metadata.distribution(name)
        rows.append(f"| {name} | {version} | {licence(dist)} |")
    (ROOT / "docs/dependency-licenses.md").write_text(
        "# Dependency licences\n\nGenerated by `scripts/list_dependency_licenses.py` from each pinned package's own "
        "metadata. Check a package's source before relying on a licence marked as not stated.\n\n"
        "| Package | Version | Licence |\n|---|---|---|\n" + "\n".join(rows) + "\n")
    print(f"Listed {len(rows)} packages")


if __name__ == "__main__":
    main()
